import React, { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import {
  Shield,
  ArrowLeft,
  AlertTriangle,
  CheckCircle,
  AlertCircle,
  HelpCircle,
  ChevronDown,
  ChevronRight,
  ExternalLink,
  Clock,
  Target,
  FileText,
  Brain,
  Award,
  TrendingUp,
  Info,
  XCircle,
  Eye,
  Download,
  Copy,
  Mail,
  Link as LinkIcon,
  Share2
} from 'lucide-react';
import { useResume } from '../context/ResumeContext';
import { useToast } from '../context/ToastContext';
import { runVerificationEngine, generateVerificationSummary } from '../utils/verificationEngine';
import { generatePDFReport, generateTextReport, copyToClipboard, shareViaEmail, getShareableLink, ExportData } from '../utils/exportReport';
import { VerificationResult, Claim, VerificationStatus, RiskLevel } from '../types/verification';

const VerificationPage: React.FC = () => {
  const { currentResume } = useResume();
  const { showToast } = useToast();
  const [verificationResult, setVerificationResult] = useState<VerificationResult | null>(null);
  const [selectedClaim, setSelectedClaim] = useState<Claim | null>(null);
  const [expandedSections, setExpandedSections] = useState<Set<string>>(new Set(['overview']));
  const [showShareMenu, setShowShareMenu] = useState(false);

  useEffect(() => {
    if (currentResume) {
      const result = runVerificationEngine(currentResume);
      setVerificationResult(result);
    }
  }, [currentResume]);

  const handleExportPDF = () => {
    if (!currentResume || !verificationResult) return;
    
    const exportData: ExportData = {
      candidateName: currentResume.candidate.name,
      fileName: currentResume.fileName,
      uploadedAt: currentResume.uploadedAt.toLocaleString(),
      overallScore: verificationResult.overallEvidenceScore,
      atsScore: 0,
      evidenceScore: verificationResult.overallEvidenceScore,
      skillMatch: 0,
      breakdown: [],
      skills: currentResume.skills.map(s => ({
        name: s.name,
        supportLevel: s.supportLevel,
        evidence: s.evidence.map(e => e.source),
      })),
      projects: currentResume.projects.map(p => ({
        name: p.name,
        depthScore: p.depthScore,
        technologies: p.technologies,
      })),
      verification: {
        overallEvidenceScore: verificationResult.overallEvidenceScore,
        supported: verificationResult.summary.supported,
        needsVerification: verificationResult.summary.needsVerification,
        suspicious: verificationResult.summary.suspicious,
        triggeredRules: verificationResult.triggeredRules.filter(r => r.triggered).map(r => r.id),
      },
    };
    
    generatePDFReport(exportData);
    showToast('success', 'Verification report generated! Use your browser\'s print dialog to save.');
  };

  const handleCopyReport = () => {
    if (!currentResume || !verificationResult) return;
    
    const summary = generateVerificationSummary(verificationResult);
    const textReport = `ResumeGuard AI Verification Report\n${'='.repeat(50)}\n\nCandidate: ${currentResume.candidate.name}\nEvidence Score: ${verificationResult.overallEvidenceScore}%\n\nSummary: ${summary}\n\nSupported: ${verificationResult.summary.supported}%\nNeeds Verification: ${verificationResult.summary.needsVerification}%\nSuspicious: ${verificationResult.summary.suspicious}%\n\nGenerated by ResumeGuard AI`;
    
    copyToClipboard(textReport).then(() => {
      showToast('success', 'Verification report copied to clipboard!');
    }).catch(() => {
      showToast('error', 'Failed to copy to clipboard');
    });
  };

  const handleShareLink = () => {
    const link = getShareableLink();
    copyToClipboard(link).then(() => {
      showToast('success', 'Link copied to clipboard!');
    }).catch(() => {
      showToast('error', 'Failed to copy link');
    });
    setShowShareMenu(false);
  };

  const handleShareEmail = () => {
    if (!currentResume || !verificationResult) return;
    
    const subject = `ResumeGuard AI Verification - ${currentResume.candidate.name}`;
    const body = `Verification report for ${currentResume.candidate.name}.\n\nEvidence Score: ${verificationResult.overallEvidenceScore}%\nSupported: ${verificationResult.summary.supported}%\nNeeds Verification: ${verificationResult.summary.needsVerification}%\nSuspicious: ${verificationResult.summary.suspicious}%\n\nView the full analysis at: ${getShareableLink()}`;
    
    shareViaEmail(subject, body);
    showToast('info', 'Opening email client...');
    setShowShareMenu(false);
  };

  if (!currentResume || !verificationResult) {
    return (
      <div className="min-h-screen bg-gradient-to-br from-slate-900 via-slate-800 to-slate-900 flex items-center justify-center">
        <div className="text-center">
          <div className="w-16 h-16 border-4 border-emerald-500/30 border-t-emerald-500 rounded-full animate-spin mx-auto mb-4" />
          <p className="text-slate-400">Running verification engine...</p>
        </div>
      </div>
    );
  }

  const getStatusIcon = (status: VerificationStatus) => {
    switch (status) {
      case 'supported': return <CheckCircle className="w-5 h-5 text-emerald-400" />;
      case 'needs_verification': return <AlertCircle className="w-5 h-5 text-amber-400" />;
      case 'suspicious': return <AlertTriangle className="w-5 h-5 text-red-400" />;
      default: return <HelpCircle className="w-5 h-5 text-slate-400" />;
    }
  };

  const getStatusColor = (status: VerificationStatus) => {
    switch (status) {
      case 'supported': return 'bg-emerald-500/10 border-emerald-500/30 text-emerald-400';
      case 'needs_verification': return 'bg-amber-500/10 border-amber-500/30 text-amber-400';
      case 'suspicious': return 'bg-red-500/10 border-red-500/30 text-red-400';
      default: return 'bg-slate-500/10 border-slate-500/30 text-slate-400';
    }
  };

  const getRiskBadge = (risk: RiskLevel) => {
    const colors = {
      low: 'bg-emerald-500/20 text-emerald-400',
      medium: 'bg-amber-500/20 text-amber-400',
      high: 'bg-orange-500/20 text-orange-400',
      critical: 'bg-red-500/20 text-red-400',
    };
    return colors[risk];
  };

  const toggleSection = (section: string) => {
    setExpandedSections(prev => {
      const next = new Set(prev);
      if (next.has(section)) {
        next.delete(section);
      } else {
        next.add(section);
      }
      return next;
    });
  };

  const summary = generateVerificationSummary(verificationResult);

  return (
    <div className="min-h-screen bg-gradient-to-br from-slate-900 via-slate-800 to-slate-900">
      {/* Header */}
      <header className="bg-slate-900/80 backdrop-blur-xl border-b border-slate-700/50 sticky top-0 z-50">
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8">
          <div className="flex items-center justify-between h-16">
            <div className="flex items-center gap-4">
              <Link to="/analysis" className="flex items-center gap-2 text-slate-400 hover:text-white transition-colors">
                <ArrowLeft className="w-5 h-5" />
                <span className="hidden sm:inline">Back to Analysis</span>
              </Link>
              <div className="w-px h-6 bg-slate-700" />
              <div className="flex items-center gap-3">
                <div className="w-10 h-10 bg-gradient-to-br from-emerald-400 to-cyan-500 rounded-xl flex items-center justify-center">
                  <Shield className="w-6 h-6 text-white" />
                </div>
                <span className="text-xl font-bold text-white">Verification Center</span>
              </div>
            </div>
            
            <div className="flex items-center gap-3">
              <div className="relative">
                <button 
                  onClick={() => setShowShareMenu(!showShareMenu)}
                  className="p-2 hover:bg-slate-700 rounded-lg transition-colors text-slate-400 hover:text-white"
                >
                  <Share2 className="w-5 h-5" />
                </button>
                
                {showShareMenu && (
                  <motion.div
                    initial={{ opacity: 0, y: 10 }}
                    animate={{ opacity: 1, y: 0 }}
                    className="absolute right-0 mt-2 w-48 bg-slate-800 border border-slate-700 rounded-xl shadow-xl overflow-hidden z-50"
                  >
                    <button
                      onClick={handleShareLink}
                      className="w-full flex items-center gap-3 px-4 py-3 hover:bg-slate-700 transition-colors text-left"
                    >
                      <LinkIcon className="w-4 h-4 text-slate-400" />
                      <span className="text-sm text-white">Copy Link</span>
                    </button>
                    <button
                      onClick={handleShareEmail}
                      className="w-full flex items-center gap-3 px-4 py-3 hover:bg-slate-700 transition-colors text-left"
                    >
                      <Mail className="w-4 h-4 text-slate-400" />
                      <span className="text-sm text-white">Share via Email</span>
                    </button>
                    <button
                      onClick={handleCopyReport}
                      className="w-full flex items-center gap-3 px-4 py-3 hover:bg-slate-700 transition-colors text-left"
                    >
                      <Copy className="w-4 h-4 text-slate-400" />
                      <span className="text-sm text-white">Copy Report</span>
                    </button>
                  </motion.div>
                )}
              </div>
              
              <button 
                onClick={handleExportPDF}
                className="flex items-center gap-2 bg-emerald-500 hover:bg-emerald-600 text-white font-medium px-4 py-2 rounded-lg transition-colors"
              >
                <Download className="w-4 h-4" />
                Export Report
              </button>
            </div>
          </div>
        </div>
      </header>

      {/* Warning Banner */}
      <div className="bg-blue-500/10 border-b border-blue-500/20">
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-3">
          <div className="flex items-center gap-3">
            <Info className="w-5 h-5 text-blue-400 flex-shrink-0" />
            <p className="text-sm text-blue-200">
              <strong>Important:</strong> Suspicion signals are indicators, not proof of fraud. 
              All findings should be verified through direct communication with the candidate.
            </p>
          </div>
        </div>
      </div>

      <main className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8">
        {/* Overview Cards */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          className="grid grid-cols-2 lg:grid-cols-5 gap-4 mb-8"
        >
          {/* Evidence Score */}
          <div className="col-span-2 bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6">
            <div className="flex items-center justify-between mb-4">
              <h2 className="text-lg font-semibold text-white">Evidence Strength Score</h2>
              <span className={`text-3xl font-bold ${
                verificationResult.overallEvidenceScore >= 70 ? 'text-emerald-400' :
                verificationResult.overallEvidenceScore >= 50 ? 'text-amber-400' : 'text-red-400'
              }`}>
                {verificationResult.overallEvidenceScore}
              </span>
            </div>
            <div className="h-3 bg-slate-700 rounded-full overflow-hidden">
              <motion.div
                className={`h-full rounded-full ${
                  verificationResult.overallEvidenceScore >= 70 ? 'bg-emerald-500' :
                  verificationResult.overallEvidenceScore >= 50 ? 'bg-amber-500' : 'bg-red-500'
                }`}
                initial={{ width: 0 }}
                animate={{ width: `${verificationResult.overallEvidenceScore}%` }}
                transition={{ duration: 1, ease: 'easeOut' }}
              />
            </div>
            <p className="text-xs text-slate-500 mt-3">
              Different from resume quality — measures evidence behind claims
            </p>
          </div>

          {/* Status Distribution */}
          <div className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6">
            <div className="flex items-center gap-2 mb-3">
              <CheckCircle className="w-5 h-5 text-emerald-400" />
              <span className="text-sm text-slate-400">Supported</span>
            </div>
            <p className="text-2xl font-bold text-emerald-400">{verificationResult.summary.supported}%</p>
          </div>

          <div className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6">
            <div className="flex items-center gap-2 mb-3">
              <AlertCircle className="w-5 h-5 text-amber-400" />
              <span className="text-sm text-slate-400">Needs Verification</span>
            </div>
            <p className="text-2xl font-bold text-amber-400">{verificationResult.summary.needsVerification}%</p>
          </div>

          <div className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6">
            <div className="flex items-center gap-2 mb-3">
              <AlertTriangle className="w-5 h-5 text-red-400" />
              <span className="text-sm text-slate-400">Suspicious</span>
            </div>
            <p className="text-2xl font-bold text-red-400">{verificationResult.summary.suspicious}%</p>
          </div>
        </motion.div>

        {/* Summary */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.1 }}
          className="bg-slate-800/30 border border-slate-700/50 rounded-2xl p-6 mb-8"
        >
          <h3 className="text-lg font-semibold text-white mb-3 flex items-center gap-2">
            <Eye className="w-5 h-5 text-cyan-400" />
            Verification Summary
          </h3>
          <p className="text-slate-300 leading-relaxed">{summary}</p>
        </motion.div>

        {/* Triggered Rules */}
        {verificationResult.triggeredRules.filter(r => r.triggered).length > 0 && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 0.2 }}
            className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6 mb-8"
          >
            <button
              onClick={() => toggleSection('rules')}
              className="flex items-center justify-between w-full"
            >
              <h3 className="text-lg font-semibold text-white flex items-center gap-2">
                <AlertTriangle className="w-5 h-5 text-amber-400" />
                Triggered Verification Rules
                <span className="text-sm font-normal text-slate-400">
                  ({verificationResult.triggeredRules.filter(r => r.triggered).length} rules)
                </span>
              </h3>
              {expandedSections.has('rules') ? <ChevronDown className="w-5 h-5 text-slate-400" /> : <ChevronRight className="w-5 h-5 text-slate-400" />}
            </button>
            
            <AnimatePresence>
              {expandedSections.has('rules') && (
                <motion.div
                  initial={{ height: 0, opacity: 0 }}
                  animate={{ height: 'auto', opacity: 1 }}
                  exit={{ height: 0, opacity: 0 }}
                  className="mt-4 space-y-3 overflow-hidden"
                >
                  {verificationResult.triggeredRules.filter(r => r.triggered).map((rule) => (
                    <div
                      key={rule.id}
                      className={`p-4 rounded-xl border ${
                        rule.severity === 'high' ? 'bg-red-500/10 border-red-500/30' :
                        rule.severity === 'medium' ? 'bg-amber-500/10 border-amber-500/30' :
                        'bg-slate-700/30 border-slate-600/30'
                      }`}
                    >
                      <div className="flex items-start justify-between gap-4">
                        <div>
                          <div className="flex items-center gap-2 mb-1">
                            <span className="text-xs font-mono text-slate-500">{rule.id}</span>
                            <span className={`text-xs px-2 py-0.5 rounded ${getRiskBadge(rule.severity)}`}>
                              {rule.severity.toUpperCase()}
                            </span>
                          </div>
                          <h4 className="font-medium text-white">{rule.name}</h4>
                          <p className="text-sm text-slate-400 mt-1">{rule.description}</p>
                        </div>
                      </div>
                      {rule.evidence.length > 0 && (
                        <div className="mt-3 flex flex-wrap gap-2">
                          {rule.evidence.slice(0, 3).map((ev, i) => (
                            <span key={i} className="text-xs px-2 py-1 bg-slate-700 rounded text-slate-300">
                              {ev.length > 50 ? ev.slice(0, 50) + '...' : ev}
                            </span>
                          ))}
                        </div>
                      )}
                      <div className="mt-3 p-3 bg-slate-800/50 rounded-lg">
                        <p className="text-sm text-cyan-300">
                          <strong>Recommendation:</strong> {rule.recommendation}
                        </p>
                      </div>
                    </div>
                  ))}
                </motion.div>
              )}
            </AnimatePresence>
          </motion.div>
        )}

        {/* Claim Explorer */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.3 }}
          className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6 mb-8"
        >
          <button
            onClick={() => toggleSection('claims')}
            className="flex items-center justify-between w-full"
          >
            <h3 className="text-lg font-semibold text-white flex items-center gap-2">
              <Target className="w-5 h-5 text-purple-400" />
              Claim Explorer
              <span className="text-sm font-normal text-slate-400">
                ({verificationResult.claimAnalysis.length} claims analyzed)
              </span>
            </h3>
            {expandedSections.has('claims') ? <ChevronDown className="w-5 h-5 text-slate-400" /> : <ChevronRight className="w-5 h-5 text-slate-400" />}
          </button>
          
          <AnimatePresence>
            {expandedSections.has('claims') && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: 'auto', opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                className="mt-4 overflow-hidden"
              >
                <div className="space-y-3 max-h-[600px] overflow-y-auto pr-2">
                  {verificationResult.claimAnalysis.map((claim) => (
                    <div
                      key={claim.id}
                      onClick={() => setSelectedClaim(selectedClaim?.id === claim.id ? null : claim)}
                      className={`p-4 rounded-xl border cursor-pointer transition-all ${
                        selectedClaim?.id === claim.id
                          ? 'bg-slate-700/50 border-cyan-500/50'
                          : 'bg-slate-700/30 border-slate-600/30 hover:border-slate-500/50'
                      }`}
                    >
                      <div className="flex items-start gap-3">
                        {getStatusIcon(claim.verificationStatus)}
                        <div className="flex-1 min-w-0">
                          <p className="text-sm text-white line-clamp-2">{claim.claim}</p>
                          <div className="flex items-center gap-3 mt-2">
                            <span className="text-xs text-slate-500">{claim.source}</span>
                            <span className={`text-xs px-2 py-0.5 rounded ${getStatusColor(claim.verificationStatus)}`}>
                              {claim.verificationStatus.replace('_', ' ')}
                            </span>
                            <span className="text-xs text-slate-400">
                              Evidence: {claim.evidenceStrength}%
                            </span>
                          </div>
                        </div>
                      </div>
                      
                      {/* Expanded Claim Details */}
                      <AnimatePresence>
                        {selectedClaim?.id === claim.id && (
                          <motion.div
                            initial={{ height: 0, opacity: 0 }}
                            animate={{ height: 'auto', opacity: 1 }}
                            exit={{ height: 0, opacity: 0 }}
                            className="mt-4 pt-4 border-t border-slate-600/50 overflow-hidden"
                          >
                            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                              <div>
                                <h4 className="text-sm font-medium text-white mb-2">Evidence Found</h4>
                                {claim.evidenceFound.length > 0 ? (
                                  <ul className="space-y-2">
                                    {claim.evidenceFound.map((ev, i) => (
                                      <li key={i} className="flex items-start gap-2 text-sm">
                                        <CheckCircle className="w-4 h-4 text-emerald-400 flex-shrink-0 mt-0.5" />
                                        <div>
                                          <span className="text-slate-300">{ev.source}</span>
                                          <p className="text-xs text-slate-500">{ev.description}</p>
                                        </div>
                                      </li>
                                    ))}
                                  </ul>
                                ) : (
                                  <p className="text-sm text-slate-500">No direct evidence found</p>
                                )}
                              </div>
                              
                              <div>
                                <h4 className="text-sm font-medium text-white mb-2">Missing Evidence</h4>
                                {claim.missingEvidence.length > 0 ? (
                                  <ul className="space-y-2">
                                    {claim.missingEvidence.map((missing, i) => (
                                      <li key={i} className="flex items-start gap-2 text-sm">
                                        <XCircle className="w-4 h-4 text-red-400 flex-shrink-0 mt-0.5" />
                                        <span className="text-slate-300">{missing}</span>
                                      </li>
                                    ))}
                                  </ul>
                                ) : (
                                  <p className="text-sm text-emerald-400">All key evidence present</p>
                                )}
                                
                                {claim.suggestedQuestions.length > 0 && (
                                  <>
                                    <h4 className="text-sm font-medium text-white mt-4 mb-2">Suggested Verification Questions</h4>
                                    <ul className="space-y-1">
                                      {claim.suggestedQuestions.map((q, i) => (
                                        <li key={i} className="text-sm text-cyan-300">• {q}</li>
                                      ))}
                                    </ul>
                                  </>
                                )}
                              </div>
                            </div>
                          </motion.div>
                        )}
                      </AnimatePresence>
                    </div>
                  ))}
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </motion.div>

        {/* Skill Verification */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.4 }}
          className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6 mb-8"
        >
          <button
            onClick={() => toggleSection('skills')}
            className="flex items-center justify-between w-full"
          >
            <h3 className="text-lg font-semibold text-white flex items-center gap-2">
              <Brain className="w-5 h-5 text-blue-400" />
              Skill Verification
              <span className="text-sm font-normal text-slate-400">
                ({verificationResult.skillVerification.length} skills)
              </span>
            </h3>
            {expandedSections.has('skills') ? <ChevronDown className="w-5 h-5 text-slate-400" /> : <ChevronRight className="w-5 h-5 text-slate-400" />}
          </button>
          
          <AnimatePresence>
            {expandedSections.has('skills') && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: 'auto', opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                className="mt-4 overflow-hidden"
              >
                <div className="overflow-x-auto">
                  <table className="w-full">
                    <thead>
                      <tr className="border-b border-slate-700/50">
                        <th className="text-left px-4 py-3 text-sm font-medium text-slate-400">Skill</th>
                        <th className="text-left px-4 py-3 text-sm font-medium text-slate-400">Mentions</th>
                        <th className="text-left px-4 py-3 text-sm font-medium text-slate-400">Evidence Sources</th>
                        <th className="text-left px-4 py-3 text-sm font-medium text-slate-400">Evidence Score</th>
                        <th className="text-left px-4 py-3 text-sm font-medium text-slate-400">Status</th>
                      </tr>
                    </thead>
                    <tbody>
                      {verificationResult.skillVerification.map((skill) => (
                        <tr key={skill.skillId} className="border-b border-slate-700/30">
                          <td className="px-4 py-3">
                            <div className="flex items-center gap-2">
                              {getStatusIcon(skill.status)}
                              <span className="font-medium text-white">{skill.skillName}</span>
                            </div>
                          </td>
                          <td className="px-4 py-3 text-sm text-slate-400">{skill.mentionCount}</td>
                          <td className="px-4 py-3">
                            <div className="flex flex-wrap gap-1">
                              {skill.evidenceSources.slice(0, 2).map((src, i) => (
                                <span key={i} className="text-xs px-2 py-1 bg-slate-700 rounded text-slate-300">
                                  {src}
                                </span>
                              ))}
                              {skill.evidenceSources.length > 2 && (
                                <span className="text-xs px-2 py-1 bg-slate-700 rounded text-slate-400">
                                  +{skill.evidenceSources.length - 2}
                                </span>
                              )}
                            </div>
                          </td>
                          <td className="px-4 py-3">
                            <div className="flex items-center gap-2">
                              <div className="w-16 h-2 bg-slate-700 rounded-full overflow-hidden">
                                <div
                                  className={`h-full rounded-full ${
                                    skill.evidenceScore >= 70 ? 'bg-emerald-500' :
                                    skill.evidenceScore >= 40 ? 'bg-amber-500' : 'bg-red-500'
                                  }`}
                                  style={{ width: `${skill.evidenceScore}%` }}
                                />
                              </div>
                              <span className="text-sm text-slate-400">{skill.evidenceScore}%</span>
                            </div>
                          </td>
                          <td className="px-4 py-3">
                            <span className={`text-xs px-2.5 py-1 rounded-full ${getStatusColor(skill.status)}`}>
                              {skill.status.replace('_', ' ')}
                            </span>
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </motion.div>
            )}
          </AnimatePresence>
        </motion.div>

        {/* Timeline Analysis */}
        {verificationResult.timelineAnalysis.issues.length > 0 && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 0.5 }}
            className="bg-slate-800/50 border border-amber-500/30 rounded-2xl p-6 mb-8"
          >
            <h3 className="text-lg font-semibold text-white flex items-center gap-2 mb-4">
              <Clock className="w-5 h-5 text-amber-400" />
              Timeline Issues Detected
            </h3>
            <div className="space-y-3">
              {verificationResult.timelineAnalysis.issues.map((issue) => (
                <div key={issue.id} className="p-4 bg-amber-500/10 rounded-xl border border-amber-500/20">
                  <div className="flex items-start justify-between gap-4">
                    <div>
                      <span className={`text-xs px-2 py-0.5 rounded ${getRiskBadge(issue.severity)}`}>
                        {issue.severity.toUpperCase()}
                      </span>
                      <p className="text-sm text-white mt-2">{issue.description}</p>
                    </div>
                  </div>
                  <div className="mt-3 p-3 bg-slate-800/50 rounded-lg">
                    <p className="text-sm text-cyan-300">
                      <strong>Recommendation:</strong> {issue.recommendation}
                    </p>
                  </div>
                </div>
              ))}
            </div>
          </motion.div>
        )}

        {/* Project Credibility */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.6 }}
          className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6 mb-8"
        >
          <button
            onClick={() => toggleSection('projects')}
            className="flex items-center justify-between w-full"
          >
            <h3 className="text-lg font-semibold text-white flex items-center gap-2">
              <Award className="w-5 h-5 text-purple-400" />
              Project Credibility Analysis
            </h3>
            {expandedSections.has('projects') ? <ChevronDown className="w-5 h-5 text-slate-400" /> : <ChevronRight className="w-5 h-5 text-slate-400" />}
          </button>
          
          <AnimatePresence>
            {expandedSections.has('projects') && (
              <motion.div
                initial={{ height: 0, opacity: 0 }}
                animate={{ height: 'auto', opacity: 1 }}
                exit={{ height: 0, opacity: 0 }}
                className="mt-4 grid grid-cols-1 md:grid-cols-2 gap-4 overflow-hidden"
              >
                {verificationResult.projectCredibility.map((proj) => (
                  <div key={proj.projectId} className="p-4 bg-slate-700/30 rounded-xl border border-slate-600/30">
                    <div className="flex items-center justify-between mb-3">
                      <h4 className="font-medium text-white">{proj.projectName}</h4>
                      <span className={`text-sm font-medium ${
                        proj.credibilityScore >= 70 ? 'text-emerald-400' :
                        proj.credibilityScore >= 40 ? 'text-amber-400' : 'text-red-400'
                      }`}>
                        {proj.credibilityScore}/100
                      </span>
                    </div>
                    
                    <div className="grid grid-cols-2 gap-2 text-xs mb-3">
                      {[
                        { label: 'Problem', present: proj.hasProblem },
                        { label: 'Solution', present: proj.hasImplementation },
                        { label: 'Tools', present: proj.hasTechnology },
                        { label: 'Role', present: proj.hasRole },
                        { label: 'Deploy', present: proj.hasDeployment },
                        { label: 'Metrics', present: proj.hasMetrics },
                        { label: 'Public link', present: proj.hasGitHub },
                        { label: 'Demo', present: proj.hasDemo },
                      ].map((item, i) => (
                        <div key={i} className="flex items-center gap-1">
                          {item.present ? (
                            <CheckCircle className="w-3 h-3 text-emerald-400" />
                          ) : (
                            <XCircle className="w-3 h-3 text-slate-600" />
                          )}
                          <span className={item.present ? 'text-slate-300' : 'text-slate-500'}>{item.label}</span>
                        </div>
                      ))}
                    </div>
                    
                    {proj.flags.length > 0 && (
                      <div className="pt-3 border-t border-slate-600/50">
                        {proj.flags.map((flag, i) => (
                          <p key={i} className="text-xs text-amber-400">• {flag}</p>
                        ))}
                      </div>
                    )}
                  </div>
                ))}
              </motion.div>
            )}
          </AnimatePresence>
        </motion.div>

        {/* Language Analysis */}
        {verificationResult.languageAnalysis.findings.length > 0 && (
          <motion.div
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: 0.7 }}
            className="bg-slate-800/50 border border-slate-700/50 rounded-2xl p-6 mb-8"
          >
            <h3 className="text-lg font-semibold text-white flex items-center gap-2 mb-4">
              <FileText className="w-5 h-5 text-cyan-400" />
              Language Analysis
            </h3>
            
            <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
              <div>
                <h4 className="text-sm font-medium text-white mb-2">Generic Buzzwords Detected</h4>
                {verificationResult.languageAnalysis.genericBuzzwords.length > 0 ? (
                  <div className="flex flex-wrap gap-2">
                    {verificationResult.languageAnalysis.genericBuzzwords.map((word, i) => (
                      <span key={i} className="text-xs px-2 py-1 bg-amber-500/20 text-amber-400 rounded">
                        {word}
                      </span>
                    ))}
                  </div>
                ) : (
                  <p className="text-sm text-emerald-400">No excessive buzzwords detected</p>
                )}
              </div>
              
              <div>
                <h4 className="text-sm font-medium text-white mb-2">Findings</h4>
                <ul className="space-y-2">
                  {verificationResult.languageAnalysis.findings.map((finding, i) => (
                    <li key={i} className="flex items-start gap-2 text-sm">
                      <Info className="w-4 h-4 text-blue-400 flex-shrink-0 mt-0.5" />
                      <span className="text-slate-300">{finding}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>
            
            <div className="mt-4 p-4 bg-blue-500/10 border border-blue-500/20 rounded-xl">
              <p className="text-sm text-blue-200">
                <strong>Note:</strong> This section contains analysis of language patterns. 
                Generic or templated language does not indicate falsification, 
                but may warrant stronger evidence verification.
              </p>
            </div>
          </motion.div>
        )}

        {/* Audit Trail */}
        <motion.div
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          transition={{ delay: 0.8 }}
          className="bg-slate-800/30 border border-slate-700/50 rounded-2xl p-6"
        >
          <h3 className="text-lg font-semibold text-white flex items-center gap-2 mb-4">
            <TrendingUp className="w-5 h-5 text-slate-400" />
            Audit Trail
          </h3>
          <div className="space-y-2">
            {verificationResult.auditTrail.map((entry) => (
              <div key={entry.id} className="flex items-center gap-4 text-sm">
                <span className="text-slate-500">
                  {new Date(entry.timestamp).toLocaleTimeString()}
                </span>
                <span className="text-slate-400">{entry.action.replace(/_/g, ' ')}</span>
                {entry.details && (
                  <span className="text-slate-500">
                    ({Object.entries(entry.details).map(([k, v]) => `${k}: ${v}`).join(', ')})
                  </span>
                )}
              </div>
            ))}
          </div>
        </motion.div>
      </main>
    </div>
  );
};

export default VerificationPage;
